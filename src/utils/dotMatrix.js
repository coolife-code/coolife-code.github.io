// 获取字符的点阵数据
export function getCharMatrix(char) {
  const upperChar = char.toUpperCase();
  return DOT_MATRIX_CHARS[upperChar] || DOT_MATRIX_CHARS['?'];
}

// 将文本转换为点阵数据
export function textToMatrix(text) {
  return text.split('').map(char => getCharMatrix(char));
}

// 计算点阵文本的宽度（以点为单位）
export function calculateMatrixWidth(text, dotSize = 1, spacing = 1) {
  const matrices = textToMatrix(text);
  const charWidth = 5; // 每个字符5列
  const totalDots = matrices.length * charWidth + (matrices.length - 1) * spacing;
  return totalDots * dotSize;
}
